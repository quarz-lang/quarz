    pub fn string(&self) -> Type {
        Type::class(self.builtin.string)
    }

    pub fn symbol(&self) -> Type {
        Type::class(self.builtin.symbol)
    }

    pub fn object(&self) -> Type {
        Type::class(self.builtin.object)
    }

