//! `Cog.lock`: the commit and content hash each cog of a movement is
//! pinned to.

use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::Error;

pub const LOCK: &str = "Cog.lock";

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Lock {
    pub version: u32,
    /// A digest of the dependencies listed by the manifests that can
    /// change (the application's and the patched cogs'): the lock is the
    /// resolution of those inputs.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub inputs: Option<String>,
    #[serde(default, rename = "cog")]
    pub cogs: Vec<LockedCog>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedCog {
    /// The cog's own `[cog] name`.
    pub name: String,
    pub module: String,
    /// `git+URL`, with `?subdir=DIR`.
    pub source: String,
    pub version: String,
    pub rev: String,
    pub hash: String,
    /// The sources of its dependencies.
    #[serde(default)]
    pub dependencies: Vec<String>,
}

impl Lock {
    pub fn read(dir: &Path) -> Result<Option<Lock>, Error> {
        let path = dir.join(LOCK);
        let text = match std::fs::read_to_string(&path) {
            Ok(t) => t,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(e) => return Err(Error::new(format!("{}: {e}", path.display()))),
        };
        let lock: Lock = toml::from_str(&text)
            .map_err(|e| Error::new(format!("{}: {}", path.display(), e.message())))?;
        if lock.version != 1 {
            return Err(Error::new(format!(
                "{}: version {} is not known to this quarz",
                path.display(),
                lock.version
            )));
        }
        Ok(Some(lock))
    }

    pub fn to_text(&self) -> String {
        let body = toml::to_string(self).expect("a lock serializes");
        format!("# Generated by `quarz cog`: the commit and content hash of every cog.\n{body}")
    }

    pub fn write(&self, dir: &Path) -> Result<(), Error> {
        let path = dir.join(LOCK);
        std::fs::write(&path, self.to_text())
            .map_err(|e| Error::new(format!("{}: {e}", path.display())))
    }
}
