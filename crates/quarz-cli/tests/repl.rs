//! The REPL keeps declarations, variables and tasks across inputs.

use std::io::Write;
use std::sync::{Arc, Mutex};

use quarz_cli::session::{needs_more, unfinished, Outcome, Repl, Unfinished};

struct Shared(Arc<Mutex<Vec<u8>>>);

impl Write for Shared {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0.lock().unwrap().extend_from_slice(buf);
        Ok(buf.len())
    }
    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

fn values(lines: &[&str]) -> (Vec<String>, String) {
    let buffer = Arc::new(Mutex::new(Vec::new()));
    let mut repl = Repl::new(Box::new(Shared(buffer.clone()))).unwrap();
    let mut out = Vec::new();
    for line in lines {
        match repl.feed_line(line) {
            Outcome::Incomplete => out.push("...".to_string()),
            Outcome::Errors(errs) => out.push(format!(
                "error: {}",
                errs.join("").lines().next().unwrap_or("")
            )),
            Outcome::Value(Some(v)) => out.push(format!("=> {v}")),
            Outcome::Value(None) => out.push(String::new()),
            Outcome::Exit(code) => out.push(format!("exit {code}")),
        }
    }
    let printed = String::from_utf8_lossy(&buffer.lock().unwrap()).into_owned();
    (out, printed)
}

#[test]
fn require_loads_libraries_once() {
    let (out, printed) = values(&[
        "require \"json\"",
        "JSON.parse(\"[1, 2]\").size",
        "require \"json\"",
        "require \"nope\"",
        "JSON.generate([1, nil])",
        "require_relative \"../../examples/geometry\"",
        "Geometry.distance(Point.new(3.0, 4.0), Geometry::ORIGIN)",
        "require_relative \"../../examples/geometry\"",
    ]);
    assert_eq!(
        out,
        vec![
            "",
            "=> 2",
            "",
            "error: <repl>:1:1: error: unknown library `nope`",
            "=> \"[1,null]\"",
            "",
            "=> 5.0",
            "",
        ]
    );
    assert_eq!(printed, "geometry loaded\n");
}

#[test]
fn static_statements_run_in_the_session() {
    // docs/14 §2: an input's statements run when it is entered, with the
    // `static def`s of earlier inputs and of required files.
    let dir = std::env::temp_dir().join(format!("quarz-repl-static-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(
        dir.join("lib.qz"),
        "class Model\n  static def self.prop(n: Symbol) -> Void\n    def_method(n) { n.to_s.upcase }\n  end\nend\n",
    )
    .unwrap();
    // A file and the file it requires are told apart (each its own
    // index), so the statement's callee is of another file.
    std::fs::write(
        dir.join("app.qz"),
        "require_relative \"lib\"\nclass Post < Model\n  prop :title\nend\n",
    )
    .unwrap();
    let app = dir.join("app").display().to_string();
    let (out, printed) = values(&[
        "X = begin; puts \"init\"; [1]; end",
        "X",
        &format!("require_relative \"{app}\""),
        "Post.new.title",
        "class Gen",
        "  static def self.make(n: Symbol, v: Int) -> Void",
        "    p n",
        "    def_method(n) { v }",
        "    def_field(:hits, Int, 0, var: true, reader: true)",
        "  end",
        "end",
        "class Use < Gen",
        "  make :answer, 42",
        "end",
        "Use.new.answer + Use.new.hits",
        "X",
        "Gen.make(:no, 1)",
        "class Own",
        "  static def self.own -> Void",
        "  end",
        "  own",
        "end",
        "class Foo",
        "  puts 1",
        "end",
        "class Boom < Gen",
        "  make :answer, 1",
        "  make :answer, 2",
        "end",
        "1 + 1",
    ]);
    let _ = std::fs::remove_dir_all(&dir);
    let expected: Vec<&str> = vec![
        "",
        "=> [1]",
        "",
        "=> \"TITLE\"",
        "...",
        "...",
        "...",
        "...",
        "...",
        "...",
        "",
        "...",
        "...",
        "",
        "=> 42",
        "=> [1]",
        "error: <repl>:1:1: error: `make` runs at compile time only (it reflects on a class or builds one): call it in a `static def` or a `static` statement",
        "...",
        "...",
        "...",
        "...",
        "error: <repl>:4:3: error: `own` is a `static def` of this input: a `static` statement runs only those of the files required or the inputs entered before",
        "...",
        "...",
        "error: <repl>:2:3: error: a statement in a class body must call a `static def` class method; `puts` is not one",
        "...",
        "...",
        "...",
        "error: <repl>:3:3: error: `def_method(:answer)`: `Boom` already has a method `answer` (generated by an earlier `static` statement)",
        "=> 2",
    ];
    assert_eq!(out, expected);
    // What a statement prints goes to the session's output; the earlier
    // input's constant was not initialized again by `def_field`.
    assert_eq!(printed, "init\n:answer\n:answer\n:answer\n");
}

#[test]
fn static_statements_with_requires_and_failures() {
    let dir = std::env::temp_dir().join(format!("quarz-repl-static2-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(
        dir.join("lib.qz"),
        "class Model\n  static def self.prop(n: Symbol) -> Void\n    def_method(n) { n.to_s.upcase }\n  end\nend\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("app.qz"),
        "require_relative \"lib\"\nclass A < Model\n  prop :aaa\nend\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("bad.qz"),
        "require_relative \"lib\"\nputs \"bad top level\"\nModel.prop(:x)\n",
    )
    .unwrap();
    let at = |name: &str| dir.join(name).display().to_string();
    let (out, printed) = values(&[
        &format!("require_relative \"{}\"", at("lib")),
        // A file required by an input is parsed after it: each its own
        // statements.
        &format!("require_relative \"{}\"; class B < Model", at("app")),
        "  prop :bbb",
        "end",
        "[A.new.aaa, B.new.bbb]",
        // A compile-time-only call in a required file stops it before its
        // top level runs.
        &format!("require_relative \"{}\"", at("bad")),
        // The statements of an input that failed do not run later.
        "class Gen",
        "  static def self.g(n: Symbol) -> Void",
        "    p n",
        "    def_method(n) { 1 }",
        "  end",
        "end",
        "class U < Gen; g :failed; def x -> Nope = 1; end",
        "class V < Gen; g :v; end",
        "V.new.v",
    ]);
    let _ = std::fs::remove_dir_all(&dir);
    assert_eq!(out[4], "=> [\"AAA\", \"BBB\"]", "{out:?}");
    assert!(
        out[5].contains("`prop` runs at compile time only"),
        "{out:?}"
    );
    assert!(out[12].contains("unknown constant `Nope`"), "{out:?}");
    assert_eq!(out[14], "=> 1", "{out:?}");
    assert_eq!(printed, ":v\n");
}

