//! `quarz check --expand`: what the class bodies' `static` statements
//! generated (docs/14 §5), as Quarz declarations: each class with its
//! generated members, under the statement that made them, a generated
//! method's body shown as the block it was lifted from.

use std::fmt::Write;

use quarz_lower::layout::Layout;
use quarz_syntax::ast::Visibility;
use quarz_syntax::{SourceFile, Span};
use quarz_types::world::Baked;
use quarz_types::{ClassId, MethodId, Synth, World};

/// One generated member: the statement's span, the order it was made in
/// within the statement, and its lines.
struct Member {
    by: Span,
    order: (u8, usize),
    lines: Vec<String>,
}

pub fn expand(world: &World, sources: &[SourceFile]) -> String {
    let layouts = quarz_lower::layout::compute(world);
    let file_of = |offset: u32| {
        sources
            .iter()
            .filter(|f| f.base <= offset && offset <= f.base + f.text.len() as u32)
            .max_by_key(|f| f.base)
    };
    let location = |offset: u32| match file_of(offset) {
        Some(f) => format!("{}:{}", f.name, f.line_col(offset).line),
        None => "?".to_string(),
    };
    let statement = |span: Span| -> String {
        let Some(f) = file_of(span.start) else {
            return String::new();
        };
        let at = |o: u32| (o.saturating_sub(f.base) as usize).min(f.text.len());
        let text = f.text.get(at(span.start)..at(span.end)).unwrap_or("");
        let mut lines = text.lines();
        let first = lines.next().unwrap_or("").trim_end().to_string();
        if lines.next().is_some() {
            format!("{first} …")
        } else {
            first
        }
    };
    let mut out = String::new();
    for class in &world.classes {
        let mut members: Vec<Member> = Vec::new();
        for (i, f) in class.fields.iter().enumerate() {
            let Some(default) = &f.baked_default else {
                continue;
            };
            let var = if f.mutable { "var " } else { "" };
            members.push(Member {
                by: f.span,
                order: (0, i),
                lines: vec![format!(
                    "{var}@{}: {} = {}",
                    f.name,
                    world.type_name(&f.ty),
                    baked(world, &layouts, default)
                )],
            });
        }
        let mut ids: Vec<MethodId> = class
            .methods
            .values()
            .chain(class.singleton_methods.values())
            .flatten()
            .copied()
            .filter(|m| world.method(*m).owner == class.id)
            .collect();
        ids.sort();
        ids.dedup();
        for mid in ids {
            let Some(by) = world.generated_by(mid) else {
                continue;
            };
            let m = world.method(mid);
            let visibility = match m.visibility {
                Visibility::Public => "",
                Visibility::Private => "private ",
                Visibility::Protected => "protected ",
            };
            let mut lines = Vec::new();
            match (&m.generated, &m.synth) {
                (Some(g), _) => {
                    if let Some(doc) = &g.doc {
                        lines.extend(doc.lines().map(|l| format!("# {l}").trim_end().to_string()));
                    }
                    lines.push(format!(
                        "{visibility}{} = <block at {}>",
                        crate::doc::method_signature(world, mid, None),
                        location(g.block.start)
                    ));
                }
                (None, Synth::FieldGet(f)) => lines.push(format!("{visibility}attr_reader :{f}")),
                (None, Synth::FieldSet(f)) => lines.push(format!("{visibility}attr_writer :{f}")),
                (None, _) => continue,
            }
            members.push(Member {
                by,
                order: (1, mid as usize),
                lines,
            });
        }
        if members.is_empty() {
            continue;
        }
        // By statement, in source order; within one, the fields, then the
        // methods in the order they were made.
        members.sort_by_key(|m| (m.by.start, m.order));
        if !out.is_empty() {
            out.push('\n');
        }
        let _ = writeln!(
            out,
            "{} {}  # {}",
            kind_word(world, class.id),
            class.name,
            location(class.span.start)
        );
        let mut last: Option<Span> = None;
        for m in &members {
            if last != Some(m.by) {
                if last.is_some() {
                    out.push('\n');
                }
                let _ = writeln!(
                    out,
                    "  # generated by `{}` at {}",
                    statement(m.by),
                    location(m.by.start)
                );
                last = Some(m.by);
            }
            for l in &m.lines {
                let _ = writeln!(out, "  {l}");
            }
        }
        out.push_str("end\n");
    }
    out
}

fn kind_word(world: &World, id: ClassId) -> &'static str {
    match world.class(id).kind {
        quarz_types::ClassKind::Module => "module",
        quarz_types::ClassKind::Data => "data",
        quarz_types::ClassKind::Enum => "enum",
        _ => "class",
    }
}

/// A baked value as the literal that makes it, or a `data` value as `p`
/// shows it (`Point(x: 1, y: 2)`: it was made without its `initialize`,
/// so no call of `new` would say what it holds).
fn baked(world: &World, layouts: &[Layout], b: &Baked) -> String {
    let list = |items: &[Baked]| {
        items
            .iter()
            .map(|x| baked(world, layouts, x))
            .collect::<Vec<_>>()
            .join(", ")
    };
    match b {
        Baked::Nil => "nil".to_string(),
        Baked::Bool(v) => v.to_string(),
        Baked::Int(v) => v.to_string(),
        Baked::BigInt { digits, base } => match base {
            16 => format!("0x{digits}"),
            8 => format!("0o{digits}"),
            2 => format!("0b{digits}"),
            _ => digits.clone(),
        },
        Baked::Float(v) => {
            if v.is_finite() {
                format!("{v:?}")
            } else if v.is_nan() {
                "Float::NAN".to_string()
            } else if *v > 0.0 {
                "Float::INFINITY".to_string()
            } else {
                "-Float::INFINITY".to_string()
            }
        }
        Baked::Str(s) => quote(s),
        Baked::Symbol(s) => {
            let n = s.chars().count();
            let plain = s
                .chars()
                .next()
                .is_some_and(|c| c.is_alphabetic() || c == '_')
                && s.chars().enumerate().all(|(i, c)| {
                    c.is_alphanumeric() || c == '_' || (i + 1 == n && "?!=".contains(c))
                });
            if plain {
                format!(":{s}")
            } else {
                format!(":{}", quote(s))
            }
        }
        Baked::Regexp { source, flags } => {
            // The lexer keeps no escape of the delimiter (`/a\/b/` and
            // `%r{a/b}` hold `a/b`): put one back.
            let mut out = String::from("/");
            let mut chars = source.chars();
            while let Some(c) = chars.next() {
                match c {
                    '\\' => {
                        out.push(c);
                        if let Some(next) = chars.next() {
                            out.push(next);
                        }
                    }
                    '/' => out.push_str("\\/"),
                    c => out.push(c),
                }
            }
            format!("{out}/{flags}")
        }
        Baked::Bytes(bytes) => {
            let mut s = String::from("b\"");
            for &c in bytes {
                match c {
                    b'"' => s.push_str("\\\""),
                    b'\\' => s.push_str("\\\\"),
                    b' '..=b'~' => s.push(c as char),
                    _ => {
                        let _ = write!(s, "\\x{c:02x}");
                    }
                }
            }
            s.push('"');
            s
        }
        Baked::Class(id) | Baked::Variant(id) => world.class(*id).name.clone(),
        Baked::Array(items) => format!("[{}]", list(items)),
        Baked::Hash(pairs) => {
            if pairs.is_empty() {
                return "{}".to_string();
            }
            let body = pairs
                .iter()
                .map(|(k, v)| {
                    format!(
                        "{} => {}",
                        baked(world, layouts, k),
                        baked(world, layouts, v)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("{{ {body} }}")
        }
        Baked::Range { lo, hi, exclusive } => {
            let end = |x: &Option<Box<Baked>>| {
                x.as_ref()
                    .map(|x| baked(world, layouts, x))
                    .unwrap_or_default()
            };
            let dots = if *exclusive { "..." } else { ".." };
            format!("({}{dots}{})", end(lo), end(hi))
        }
        Baked::Data(id, fields) => data(world, layouts, *id, &mut fields.iter()),
    }
}

/// A `data` value from its physical fields (`Baked::Data`), its declared
/// fields in order: one held by value takes the physical fields of its
/// own (`quarz_lower::layout`).
fn data<'a>(
    world: &World,
    layouts: &[Layout],
    id: ClassId,
    values: &mut impl Iterator<Item = &'a Baked>,
) -> String {
    let fields: Vec<String> = layouts[id as usize]
        .ivars
        .iter()
        .map(|ivar| {
            let value = match ivar.flat {
                Some(d) => data(world, layouts, d, values),
                None => values
                    .next()
                    .map_or_else(|| "?".to_string(), |v| baked(world, layouts, v)),
            };
            format!("{}: {value}", ivar.name)
        })
        .collect();
    format!("{}({})", world.class(id).name, fields.join(", "))
}

/// A string literal: double-quoted, with what would interpolate or end it
/// escaped.
fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            '#' if chars.peek() == Some(&'{') => out.push_str("\\#"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
